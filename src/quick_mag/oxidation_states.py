COMMON_OXIDATION_STATES: dict[str, tuple[int, ...]] = {
    element: tuple(
        oxidation_state
        for oxidation_state, _score in sorted(
            oxidation_state_scores.items(),
            key=lambda item: (item[1], abs(item[0]), item[0]),
        )
    )
    for element, oxidation_state_scores in DEFAULT_OXIDATION_STATE_SCORES.items()
}


def oxidation_state_score(element: str, oxidation_state: int) -> float:
    return DEFAULT_OXIDATION_STATE_SCORES.get(element, {}).get(oxidation_state, 10.0)


def common_oxidation_states(element: str) -> tuple[int, ...]:
    return COMMON_OXIDATION_STATES.get(element, ())
